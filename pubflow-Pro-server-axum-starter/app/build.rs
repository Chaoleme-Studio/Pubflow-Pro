use std::env;
use std::fs;
use std::path::{Path, PathBuf};

struct EmbeddedFile {
    const_name: &'static str,
    candidates: &'static [&'static str],
}

fn main() {
    println!("cargo:rerun-if-env-changed=ALIPAY_EMBEDDED_KEYS_DIR");
    println!("cargo:rerun-if-env-changed=PUBFLOW_ENV");
    println!("cargo:rerun-if-env-changed=ENV");
    println!("cargo:rerun-if-env-changed=APP_ENV");

    let manifest_dir = PathBuf::from(
        env::var_os("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR should be set by Cargo"),
    );
    let repo_root = manifest_dir
        .parent()
        .and_then(|server_root| server_root.parent())
        .expect("server root should live under repo root");
    let default_dir = manifest_dir
        .parent()
        .expect("app crate should live under server root")
        .join("secrets")
        .join("alipay");
    let keys_dir = env::var_os("ALIPAY_EMBEDDED_KEYS_DIR")
        .map(PathBuf::from)
        .unwrap_or(default_dir);

    println!("cargo:rerun-if-changed={}", keys_dir.display());

    let specs = [
        EmbeddedFile {
            const_name: "APP_PRIVATE_KEY",
            candidates: &[
                "app_private_key.txt",
                "应用私钥RSA2048-敏感数据，请妥善保管.txt",
            ],
        },
        EmbeddedFile {
            const_name: "APP_PUBLIC_KEY",
            candidates: &["app_public_key.txt", "应用公钥RSA2048.txt"],
        },
        EmbeddedFile {
            const_name: "ALIPAY_PUBLIC_KEY",
            candidates: &["alipay_public_key.txt", "alipayPublicKey_RSA2.txt"],
        },
        EmbeddedFile {
            const_name: "APP_CERT_SN",
            candidates: &["app_cert_sn.txt", "appCertSN.txt"],
        },
        EmbeddedFile {
            const_name: "ALIPAY_ROOT_CERT_SN",
            candidates: &["alipay_root_cert_sn.txt", "alipayRootCertSN.txt"],
        },
        EmbeddedFile {
            const_name: "APP_CERT",
            candidates: &["app_cert_public_key.crt", "appCertPublicKey.crt"],
        },
        EmbeddedFile {
            const_name: "ALIPAY_ROOT_CERT",
            candidates: &["alipay_root_cert.crt", "alipayRootCert.crt"],
        },
        EmbeddedFile {
            const_name: "ALIPAY_PUBLIC_CERT",
            candidates: &["alipay_public_cert.crt", "alipayCertPublicKey_RSA2.crt"],
        },
    ];

    let mut output = String::from("// @generated by app/build.rs\n");
    for spec in specs {
        let value = read_first_existing(&keys_dir, spec.candidates);
        output.push_str(&format!(
            "#[allow(dead_code)]\npub const {}: Option<&'static str> = {};\n",
            spec.const_name,
            rust_option_string(value)
        ));
    }

    let out_dir = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR should be set by Cargo"));
    fs::write(out_dir.join("alipay_embedded.rs"), output)
        .expect("failed to write generated alipay embedding file");
    fs::write(
        out_dir.join("pubflow_embedded_env.rs"),
        embedded_env_output(repo_root),
    )
    .expect("failed to write generated env embedding file");
}

fn read_first_existing(base_dir: &Path, candidates: &[&str]) -> Option<String> {
    for candidate in candidates {
        let path = base_dir.join(candidate);
        println!("cargo:rerun-if-changed={}", path.display());
        if !path.is_file() {
            continue;
        }
        let value = fs::read_to_string(&path).ok()?;
        let value = value.trim();
        if !value.is_empty() {
            return Some(value.to_string());
        }
    }
    None
}

fn rust_option_string(value: Option<String>) -> String {
    match value {
        Some(value) => format!("Some({value:?})"),
        None => "None".to_string(),
    }
}

fn embedded_env_output(repo_root: &Path) -> String {
    let env_name = env::var("PUBFLOW_ENV")
        .or_else(|_| env::var("ENV"))
        .or_else(|_| env::var("APP_ENV"))
        .unwrap_or_else(|_| "development".to_string());
    let env_file = repo_root.join(format!(".env.{env_name}"));
    println!("cargo:rerun-if-changed={}", env_file.display());

    let mut vars = parse_env_file(&env_file).unwrap_or_default();
    for key in ["PUBFLOW_ENV", "ENV", "APP_ENV"] {
        if !vars.iter().any(|(existing_key, _)| existing_key == key) {
            vars.push((key.to_string(), env_name.clone()));
        }
    }

    let mut output = String::from("// @generated by app/build.rs\n");
    output.push_str("pub const VARS: &[(&str, &str)] = &[\n");
    for (key, value) in vars {
        output.push_str(&format!("    ({key:?}, {value:?}),\n"));
    }
    output.push_str("];\n");
    output
}

fn parse_env_file(path: &Path) -> Option<Vec<(String, String)>> {
    let content = fs::read_to_string(path).ok()?;
    let mut vars = Vec::new();
    for raw_line in content.lines() {
        let line = raw_line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let Some((key, value)) = line.split_once('=') else {
            continue;
        };
        let key = key.trim();
        if key.is_empty()
            || !key
                .chars()
                .all(|ch| ch == '_' || ch.is_ascii_alphanumeric())
        {
            continue;
        }
        let value = unquote_env_value(value.trim());
        vars.push((key.to_string(), value));
    }
    Some(vars)
}

fn unquote_env_value(value: &str) -> String {
    if value.len() >= 2
        && ((value.starts_with('"') && value.ends_with('"'))
            || (value.starts_with('\'') && value.ends_with('\'')))
    {
        value[1..value.len() - 1].to_string()
    } else {
        value.to_string()
    }
}
